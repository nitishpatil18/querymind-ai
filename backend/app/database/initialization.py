"""Database initialisation helpers: schema, deterministic seed data and the read-only role.

Used by scripts/initialize_database.py and scripts/seed_database.py. Docker Compose applies the same
SQL files through the PostgreSQL entrypoint (database/init/*), so both paths produce the same database.
"""
from __future__ import annotations

import logging
from datetime import date
from decimal import Decimal
from pathlib import Path

import psycopg
from psycopg import sql
from sqlalchemy.engine import make_url

from app.database.seed_data import SeedData, generate

logger = logging.getLogger(__name__)

REPO_ROOT = Path(__file__).resolve().parents[3]
INIT_DIR_CANDIDATES = [REPO_ROOT / "database" / "init", Path("/database/init"), Path("../database/init")]

TABLE_COLUMNS = {
    "categories": ["category_id", "category_name", "description"],
    "customers": ["customer_id", "first_name", "last_name", "email", "city", "state", "registration_date"],
    "products": ["product_id", "product_name", "category_id", "price", "stock_quantity"],
    "orders": ["order_id", "customer_id", "order_date", "order_status", "total_amount"],
    "order_items": ["order_item_id", "order_id", "product_id", "quantity", "unit_price"],
    "payments": ["payment_id", "order_id", "payment_method", "payment_status", "payment_date", "amount"],
}
IDENTITY_COLUMN = {t: cols[0] for t, cols in TABLE_COLUMNS.items()}
INSERT_ORDER = ["categories", "customers", "products", "orders", "order_items", "payments"]


def init_dir() -> Path:
    for cand in INIT_DIR_CANDIDATES:
        if (cand / "01_schema.sql").exists():
            return cand
    raise FileNotFoundError("database/init/01_schema.sql not found")


def to_psycopg_dsn(sqlalchemy_url: str) -> str:
    url = make_url(sqlalchemy_url).set(drivername="postgresql")
    return url.render_as_string(hide_password=False)


def _lit(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, (Decimal, int, float)):
        return str(value)
    if isinstance(value, date):
        return f"'{value.isoformat()}'"
    return "'" + str(value).replace("'", "''") + "'"


def render_seed_sql(data: SeedData | None = None, batch: int = 400) -> str:
    data = data or generate()
    rows_by_table = {
        "categories": data.categories,
        "customers": data.customers,
        "products": data.products,
        "orders": data.orders,
        "order_items": data.order_items,
        "payments": data.payments,
    }
    out = [
        "-- Deterministic synthetic seed data (generated by backend/scripts/generate_seed_sql.py).",
        "-- Do not edit by hand: regenerate instead. All emails use the reserved example.com domain.",
        "BEGIN;",
    ]
    for table in INSERT_ORDER:
        rows = rows_by_table[table]
        cols = ", ".join(TABLE_COLUMNS[table])
        for i in range(0, len(rows), batch):
            chunk = rows[i : i + batch]
            values = ",\n  ".join("(" + ", ".join(_lit(v) for v in r) + ")" for r in chunk)
            out.append(f"INSERT INTO {table} ({cols}) VALUES\n  {values};")
    for table, col in IDENTITY_COLUMN.items():
        out.append(f"SELECT setval(pg_get_serial_sequence('{table}', '{col}'), (SELECT MAX({col}) FROM {table}));")
    out.append("COMMIT;")
    out.append("ANALYZE;")
    return "\n".join(out) + "\n"


def run_script(admin_url: str, script: str) -> None:
    with psycopg.connect(to_psycopg_dsn(admin_url), autocommit=True) as conn:
        conn.execute(script)  # no parameters -> multi-statement scripts are allowed


def table_exists(admin_url: str, table: str, schema: str = "public") -> bool:
    with psycopg.connect(to_psycopg_dsn(admin_url), autocommit=True) as conn:
        row = conn.execute("SELECT to_regclass(%s)", (f"{schema}.{table}",)).fetchone()
    return bool(row and row[0])


def ensure_readonly_role(admin_url: str, ro_user: str, ro_password: str, schema: str = "public") -> None:
    """Create/refresh the read-only role. Idempotent; safe to call on every start."""
    with psycopg.connect(to_psycopg_dsn(admin_url), autocommit=True) as conn:
        db = conn.execute("SELECT current_database()").fetchone()[0]
        exists = conn.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (ro_user,)).fetchone()
        ident = sql.Identifier(ro_user)
        if not exists:
            conn.execute(
                sql.SQL("CREATE ROLE {} LOGIN PASSWORD {} NOSUPERUSER NOCREATEDB NOCREATEROLE").format(
                    ident, sql.Literal(ro_password)
                )
            )
        else:
            conn.execute(sql.SQL("ALTER ROLE {} PASSWORD {}").format(ident, sql.Literal(ro_password)))
        stmts = [
            "ALTER ROLE {r} SET default_transaction_read_only = on",
            "ALTER ROLE {r} SET statement_timeout = '15s'",
            "ALTER ROLE {r} SET idle_in_transaction_session_timeout = '30s'",
            "GRANT CONNECT ON DATABASE {db} TO {r}",
            "REVOKE CREATE ON SCHEMA {s} FROM PUBLIC",
            "REVOKE CREATE ON SCHEMA {s} FROM {r}",
            "GRANT USAGE ON SCHEMA {s} TO {r}",
            "GRANT SELECT ON ALL TABLES IN SCHEMA {s} TO {r}",
            "ALTER DEFAULT PRIVILEGES IN SCHEMA {s} GRANT SELECT ON TABLES TO {r}",
        ]
        for stmt in stmts:
            conn.execute(sql.SQL(stmt).format(r=ident, db=sql.Identifier(db), s=sql.Identifier(schema)))
    logger.info("read-only role ensured", extra={"role": ro_user})


def initialize(admin_url: str, ro_user: str, ro_password: str, *, seed: bool = True, force: bool = False) -> dict:
    """Create schema + seed (when missing or forced) and make sure the read-only role exists."""
    d = init_dir()
    created = False
    if force or not table_exists(admin_url, "customers"):
        run_script(admin_url, (d / "01_schema.sql").read_text())
        created = True
    seeded = False
    if seed and (created or _is_empty(admin_url)):
        seed_file = d / "02_seed.sql"
        run_script(admin_url, seed_file.read_text() if seed_file.exists() else render_seed_sql())
        seeded = True
    ensure_readonly_role(admin_url, ro_user, ro_password)
    return {"schema_created": created, "seeded": seeded}


def _is_empty(admin_url: str) -> bool:
    with psycopg.connect(to_psycopg_dsn(admin_url), autocommit=True) as conn:
        return conn.execute("SELECT count(*) FROM customers").fetchone()[0] == 0
