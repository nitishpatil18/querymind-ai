-- QueryMind AI demo database: e-commerce schema (PostgreSQL)
-- Table and column descriptions are stored as PostgreSQL comments so the
-- schema inspector can read them dynamically.

DROP TABLE IF EXISTS payments CASCADE;
DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS customers CASCADE;

CREATE TABLE customers (
    customer_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name         VARCHAR(60)  NOT NULL,
    last_name          VARCHAR(60)  NOT NULL,
    email              VARCHAR(160) NOT NULL UNIQUE,
    city               VARCHAR(80)  NOT NULL,
    state              VARCHAR(80)  NOT NULL,
    registration_date  DATE         NOT NULL
);

CREATE TABLE categories (
    category_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name  VARCHAR(80) NOT NULL UNIQUE,
    description    TEXT
);

CREATE TABLE products (
    product_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name    VARCHAR(160)  NOT NULL,
    category_id     INTEGER       NOT NULL REFERENCES categories (category_id),
    price           NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    stock_quantity  INTEGER       NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0)
);

CREATE TABLE orders (
    order_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   INTEGER       NOT NULL REFERENCES customers (customer_id),
    order_date    DATE          NOT NULL,
    order_status  VARCHAR(20)   NOT NULL
        CHECK (order_status IN ('pending', 'processing', 'shipped', 'completed', 'cancelled')),
    total_amount  NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0)
);

CREATE TABLE order_items (
    order_item_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       INTEGER       NOT NULL REFERENCES orders (order_id),
    product_id     INTEGER       NOT NULL REFERENCES products (product_id),
    quantity       INTEGER       NOT NULL CHECK (quantity > 0),
    unit_price     NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0)
);

CREATE TABLE payments (
    payment_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        INTEGER       NOT NULL REFERENCES orders (order_id),
    payment_method  VARCHAR(30)   NOT NULL
        CHECK (payment_method IN ('credit_card', 'debit_card', 'upi', 'net_banking', 'cash_on_delivery', 'wallet')),
    payment_status  VARCHAR(20)   NOT NULL
        CHECK (payment_status IN ('pending', 'completed', 'failed', 'refunded')),
    payment_date    DATE,
    amount          NUMERIC(12,2) NOT NULL CHECK (amount >= 0)
);

CREATE INDEX idx_customers_state        ON customers (state);
CREATE INDEX idx_products_category      ON products (category_id);
CREATE INDEX idx_orders_customer        ON orders (customer_id);
CREATE INDEX idx_orders_date            ON orders (order_date);
CREATE INDEX idx_orders_status          ON orders (order_status);
CREATE INDEX idx_order_items_order      ON order_items (order_id);
CREATE INDEX idx_order_items_product    ON order_items (product_id);
CREATE INDEX idx_payments_order         ON payments (order_id);
CREATE INDEX idx_payments_status        ON payments (payment_status);

COMMENT ON TABLE customers   IS 'Registered customers of the online store, with their location and registration date.';
COMMENT ON TABLE categories  IS 'Product categories used to group the product catalog.';
COMMENT ON TABLE products    IS 'Catalog of products for sale, each belonging to one category.';
COMMENT ON TABLE orders      IS 'Customer orders. One row per order; line items are in order_items.';
COMMENT ON TABLE order_items IS 'Line items of an order: which product, how many, and the unit price charged.';
COMMENT ON TABLE payments    IS 'Payment attempts for orders, with method, status and amount.';

COMMENT ON COLUMN customers.registration_date IS 'Date the customer registered.';
COMMENT ON COLUMN customers.state             IS 'Indian state of the customer, for example Karnataka.';
COMMENT ON COLUMN products.price              IS 'Current list price of the product.';
COMMENT ON COLUMN orders.order_status         IS 'Lifecycle status: pending, processing, shipped, completed or cancelled.';
COMMENT ON COLUMN orders.total_amount         IS 'Order total, equal to the sum of quantity * unit_price over its order_items.';
COMMENT ON COLUMN order_items.unit_price      IS 'Price per unit charged at the time of the order (can differ from products.price).';
COMMENT ON COLUMN payments.payment_status     IS 'pending, completed, failed or refunded.';
COMMENT ON COLUMN payments.payment_date       IS 'Date the payment was made; NULL while the payment is pending.';
